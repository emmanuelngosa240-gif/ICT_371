SELECT record_id, status FROM s4_clinic.dispensing_records ORDER BY record_id;

-- Step 7
CREATE OR REPLACE PROCEDURE s4_clinic.show_low_stock()
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR FOR
        SELECT medicine_name, stock_quantity
        FROM s4_clinic.medicines
        WHERE stock_quantity <= 2
        ORDER BY medicine_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low stock: % (% remaining)', v_item.medicine_name, v_item.stock_quantity;
    END LOOP;
    CLOSE c_low;
END; $$;

CALL s4_clinic.show_low_stock();

