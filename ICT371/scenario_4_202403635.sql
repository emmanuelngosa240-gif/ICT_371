-- Step 6
CREATE OR REPLACE PROCEDURE s4_clinic.reverse_dispensing(p_record_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_medicine_id integer;
    v_quantity integer;
BEGIN
    SELECT medicine_id, quantity INTO v_medicine_id, v_quantity
    FROM s4_clinic.dispensing_records
    WHERE record_id = p_record_id AND status = 'DISPENSED'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active dispensing record with ID %', p_record_id;
        RETURN;
    END IF;

    UPDATE s4_clinic.dispensing_records
    SET status = 'REVERSED'
    WHERE record_id = p_record_id;

    UPDATE s4_clinic.medicines
    SET stock_quantity = stock_quantity + v_quantity
    WHERE medicine_id = v_medicine_id;

    RAISE NOTICE 'Dispensing record % reversed; % units restored', p_record_id, v_quantity;
END; $$;

CALL s4_clinic.reverse_dispensing(1);
