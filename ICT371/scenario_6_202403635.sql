-- Step 7
CREATE OR REPLACE PROCEDURE s6_events.show_full_or_nearly_full()
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR FOR
        SELECT event_name, available_seats
        FROM s6_events.events
        WHERE available_seats <= 2
        ORDER BY event_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Full or nearly full: % (% seats left)', v_item.event_name, v_item.available_seats;
    END LOOP;
    CLOSE c_low;
END; $$;

CALL s6_events.show_full_or_nearly_full();

