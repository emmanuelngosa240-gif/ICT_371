CREATE OR REPLACE PROCEDURE s6_events.cancel_booking(p_booking_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_event_id integer;
    v_seats integer;
BEGIN
    SELECT event_id, seats INTO v_event_id, v_seats
    FROM s6_events.bookings
    WHERE booking_id = p_booking_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active booking with ID %', p_booking_id;
        RETURN;
    END IF;

    UPDATE s6_events.bookings
    SET status = 'CANCELLED'
    WHERE booking_id = p_booking_id;

    UPDATE s6_events.events
    SET available_seats = available_seats + v_seats
    WHERE event_id = v_event_id;

    RAISE NOTICE 'Booking % cancelled; % seats released', p_booking_id, v_seats;
END; $$;

