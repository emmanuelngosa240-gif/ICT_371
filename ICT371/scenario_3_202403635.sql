SELECT allocation_id, status FROM s3_hostel.allocations ORDER BY allocation_id;

-- Step 7
CREATE OR REPLACE PROCEDURE s3_hostel.show_full_or_nearly_full()
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR FOR
        SELECT room_number, available_spaces
        FROM s3_hostel.hostel_rooms
        WHERE available_spaces <= 1
        ORDER BY room_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Full or nearly full: % (% spaces left)', v_item.room_number, v_item.available_spaces;
    END LOOP;
    CLOSE c_low;
END; $$;

CALL s3_hostel.show_full_or_nearly_full();

