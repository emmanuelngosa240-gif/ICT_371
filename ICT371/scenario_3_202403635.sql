-- Step 6
CREATE OR REPLACE PROCEDURE s3_hostel.check_out(p_allocation_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_room_id integer;
BEGIN
    SELECT room_id INTO v_room_id
    FROM s3_hostel.allocations
    WHERE allocation_id = p_allocation_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active allocation with ID %', p_allocation_id;
        RETURN;
    END IF;

    UPDATE s3_hostel.allocations
    SET status = 'COMPLETED'
    WHERE allocation_id = p_allocation_id;

    UPDATE s3_hostel.hostel_rooms
    SET available_spaces = available_spaces + 1
    WHERE room_id = v_room_id;

    RAISE NOTICE 'Allocation % checked out; 1 space released', p_allocation_id;
END; $$;

CALL s3_hostel.check_out(1);
