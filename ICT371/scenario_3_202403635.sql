-- Step 1
CREATE TABLE s3_hostel.hostel_rooms (
    room_id integer PRIMARY KEY,
    room_number text NOT NULL,
    available_spaces integer NOT NULL CHECK (available_spaces >= 0)
);

CREATE TABLE s3_hostel.allocations (
    allocation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id integer NOT NULL REFERENCES s3_hostel.hostel_rooms(room_id),
    student_number text NOT NULL,
    status text NOT NULL CHECK (status IN ('ACTIVE','COMPLETED'))
);

