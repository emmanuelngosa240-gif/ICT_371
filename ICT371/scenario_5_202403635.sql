-- Step 6
CREATE OR REPLACE PROCEDURE s5_tools.return_tool(p_loan_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_tool_id integer;
    v_quantity integer;
BEGIN
    SELECT tool_id, quantity INTO v_tool_id, v_quantity
    FROM s5_tools.tool_loans
    WHERE loan_id = p_loan_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active loan with ID %', p_loan_id;
        RETURN;
    END IF;

    UPDATE s5_tools.tool_loans
    SET status = 'RETURNED'
    WHERE loan_id = p_loan_id;

    UPDATE s5_tools.tools
    SET available_quantity = available_quantity + v_quantity
    WHERE tool_id = v_tool_id;

    RAISE NOTICE 'Loan % returned; % units restored', p_loan_id, v_quantity;
END; $$;

CALL s5_tools.return_tool(1);
