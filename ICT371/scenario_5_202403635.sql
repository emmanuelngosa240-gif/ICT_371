SELECT loan_id, status FROM s5_tools.tool_loans ORDER BY loan_id;

-- Step 7
CREATE OR REPLACE PROCEDURE s5_tools.show_low_availability()
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR FOR
        SELECT tool_name, available_quantity
        FROM s5_tools.tools
        WHERE available_quantity <= 2
        ORDER BY tool_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low availability: % (% remaining)', v_item.tool_name, v_item.available_quantity;
    END LOOP;
    CLOSE c_low;
END; $$;

CALL s5_tools.show_low_availability();

