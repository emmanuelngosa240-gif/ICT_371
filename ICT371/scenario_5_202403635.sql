-- Step 4
CREATE OR REPLACE PROCEDURE s5_tools.issue_tool(
    p_tool_id integer,
    p_student_number text,
    p_quantity integer
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_available integer;
    v_loan_id integer;
BEGIN
    IF p_quantity <= 0 THEN
        RAISE EXCEPTION 'Quantity must be positive' USING ERRCODE = '22023';
    END IF;

    SELECT available_quantity INTO v_available
    FROM s5_tools.tools
    WHERE tool_id = p_tool_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'Tool % does not exist', p_tool_id;
        RETURN;
    ELSIF v_available < p_quantity THEN
        RAISE NOTICE 'Insufficient stock: only % available', v_available;
        RETURN;
    END IF;

    UPDATE s5_tools.tools
    SET available_quantity = available_quantity - p_quantity
    WHERE tool_id = p_tool_id;

    INSERT INTO s5_tools.tool_loans (tool_id, student_number, quantity, status)
    VALUES (p_tool_id, p_student_number, p_quantity, 'ACTIVE')
    RETURNING loan_id INTO v_loan_id;

    RAISE NOTICE 'Tool loan % created for student %', v_loan_id, p_student_number;
END; $$;

